"""Generates git_version.h and lfs_core_abi_stamp.h (see cmake/GenerateGitVersion.cmake
and cmake/GenerateCoreAbiStamp.cmake)."""

import argparse
import hashlib
import pathlib
import re


def read_status(path: str) -> dict[str, str]:
    values = {}
    for line in pathlib.Path(path).read_text(encoding="utf-8").splitlines():
        key, _, value = line.partition(" ")
        values[key] = value
    return values


def write_if_changed(path: str, content: str) -> None:
    pathlib.Path(path).write_text(content, encoding="utf-8", newline="\n")


def git_version(args: argparse.Namespace) -> None:
    status = read_status(args.status)
    commit = status.get("STABLE_GIT_COMMIT_HASH_SHORT", "unknown") or "unknown"
    tagged = status.get("STABLE_GIT_TAGGED_VERSION", "unknown") or "unknown"
    # A build past the last release tag is named after the declared project version.
    match = re.fullmatch(r"v[0-9][0-9.]*-([0-9]+)-g([0-9a-f]+)(-dirty)?", tagged)
    if match:
        tagged = f"v{args.version}-dev-{match.group(1)}-g{match.group(2)}{match.group(3) or ''}"
    write_if_changed(
        args.out,
        f'#pragma once\n#define GIT_COMMIT_HASH_SHORT "{commit}"\n#define GIT_TAGGED_VERSION "{tagged}"\n',
    )


def core_abi_stamp(args: argparse.Namespace) -> None:
    material = "|".join(args.material)
    for source in sorted(args.inputs):
        material += "|" + hashlib.sha256(pathlib.Path(source).read_bytes()).hexdigest()
    stamp = hashlib.sha256(material.encode("utf-8")).hexdigest()
    template = pathlib.Path(args.template).read_text(encoding="utf-8")
    content = template.replace("@LFS_CORE_ABI_STAMP@", stamp).replace("Generated by CMake", "Generated by Bazel")
    write_if_changed(args.out, content)


def main() -> None:
    parser = argparse.ArgumentParser()
    commands = parser.add_subparsers(dest="command", required=True)

    git = commands.add_parser("git_version")
    git.add_argument("--status", required=True, help="bazel-out/stable-status.txt")
    git.add_argument("--version", required=True)
    git.add_argument("--out", required=True)
    git.set_defaults(func=git_version)

    abi = commands.add_parser("core_abi_stamp")
    abi.add_argument("--template", required=True)
    abi.add_argument("--out", required=True)
    abi.add_argument("--material", action="append", default=[])
    abi.add_argument("inputs", nargs="*")
    abi.set_defaults(func=core_abi_stamp)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
